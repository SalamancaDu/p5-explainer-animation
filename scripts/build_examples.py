"""Build standalone examples from the single maintained Skill runtime (stdlib only)."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / 'skills/p5-explainer-animation'
SCENES = [
    ('flower', 'a', 'collage', '纸片开花', True),
    ('flower', 'b', 'doodle', '想法开花', True),
    ('flower', 'c', 'painting', '笔触开花', False),
    ('quantity', 'index', 'quantity', '六段素材，分成两组', True),
]

def products():
    template = (SKILL / 'assets/index.template.html').read_text(encoding='utf-8')
    license_text = (ROOT / 'LICENSE').read_text(encoding='utf-8').strip()
    for folder, name, source, title, loop in SCENES:
        config = dict(title=title, fileName=source, width=1920, height=1080,
                      fps=30, seconds=6, seed=2077, loop=loop,
                      fontFamily='Noto Sans SC', fontWeight=900,
                      fontSample='想法开花归组示例六段素材分成两组123456×=',
                      fontCss='https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@900&display=swap',
                      p5Url='https://cdn.jsdelivr.net/npm/p5@1.11.11/lib/p5.min.js')
        scene = (ROOT / f'examples/{folder}/source/{source}.js').read_text(encoding='utf-8')
        script = 'const CONFIG = Object.freeze(' + json.dumps(config, ensure_ascii=False, indent=2) + ');\n\n' + scene
        html = re.sub(r'(<script id="animation-scene">)[\s\S]*?</script>',
                      lambda m: m[1] + '\n' + script + '\n</script>', template)
        html = html.replace('<title>口播配画面 · 素材拼贴</title>', f'<title>{title}</title>')
        html = html.replace('素材主题的复古拼贴动画', title)
        notice = ('<!-- Generated by scripts/build_examples.py. Edit the scene source, then rebuild.\n'
                  + license_text + '\nExternal p5.js 1.11.11: LGPL 2.1, https://github.com/processing/p5.js/tree/v1.11.11\n'
                  + 'External Noto Sans SC: SIL OFL 1.1, https://github.com/google/fonts/tree/main/ofl/notosanssc\n-->')
        html = html.replace('<!doctype html>', '<!doctype html>\n' + notice, 1)
        yield ROOT / f'examples/{folder}/{name}.html', html
    compare = (SKILL / 'assets/compare.template.html').read_text(encoding='utf-8')
    compare = compare.replace('同一句话，三个方向', '把零散的想法，变成一朵花')
    compare = compare.replace('三色网点、白纸芯、撕边纸片、错峰拍入。', '错版网点、白纸芯、撕边花瓣，零散纸片组成花朵。')
    compare = compare.replace('<!-- Update these descriptions to match the actual three completed scenes. -->', '<!-- Built from the maintained comparison runtime. -->')
    # Descriptions belong to these completed scenes, not generic template defaults.
    descriptions = [
      ('A · 复古拼贴', '三色网点、白纸芯、撕边花瓣。', '#A6AD82 · #EDCE42 · #C54B39', '纸片拍入并组装，最后一秒完全定格。'),
      ('B · 手绘涂鸦', '压力线条、逐笔画花、错位填色。', '#F4EEDD · #292B25 · #C54B39', '人物产生想法，箭头引出花朵，尾段线条微动。'),
      ('C · 水彩作画', '宽笔刷痕、透明叠色、沉积边和干笔。', '#F1E8D4 · #65826B · #C67460', '六秒比较版：前 80% 作画，后 20% 花枝微动。'),
    ]
    for letter, (title, method, colors, rhythm) in zip('abc', descriptions):
        article = f'<article><iframe title="{title}" data-file="{letter}.html"></iframe><h2>{title}</h2><p>画法：{method}</p><p>配色：<code>{colors}</code></p><p>节奏：{rhythm}</p></article>'
        compare = re.sub(r'<article><iframe[^>]*data-file="' + letter + r'.html"[\s\S]*?</article>', lambda m: article, compare)
    yield ROOT / 'examples/flower/compare.html', compare
    # The installable folder carries its notices even when copied on its own.
    # Root notices are authoritative; these copies are generated and checked.
    yield SKILL / 'LICENSE', (ROOT / 'LICENSE').read_text(encoding='utf-8')
    yield SKILL / 'THIRD_PARTY_NOTICES.md', (ROOT / 'THIRD_PARTY_NOTICES.md').read_text(encoding='utf-8').replace('at the repository root', 'in this folder')
    for path in (ROOT / 'licenses').glob('*.txt'):
        yield SKILL / 'licenses' / path.name, path.read_text(encoding='utf-8')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in products():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Out of date: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
        print(('CHECK ' if args.check else 'BUILD ') + str(path.relative_to(ROOT)))
